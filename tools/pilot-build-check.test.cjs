const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lancer-build-'));
const tool = path.join(__dirname, 'pilot-build.cjs');
const put = (name, value) => fs.writeFileSync(path.join(dir, name + '.json'), JSON.stringify(value));
const run = (...args) => spawnSync(process.execPath, [tool, ...args], { encoding: 'utf8' });
try {
  put('frames', [{id:'f',name:'Test Frame',source:'GMS',license_level:0,stats:{sp:6},mounts:['Main/Aux','Flex']}]);
  put('weapons', [{id:'w',name:'Test Gun',source:'GMS',license_level:0,mount:'Main'}, {id:'aux',name:'Sidearm',source:'GMS',license_level:0,mount:'Auxiliary'}, {id:'locked',name:'Locked Gun',source:'HORUS',license:'Goblin',license_level:1,mount:'Main',sp:1}]);
  put('systems', [{id:'s',name:'Shield',source:'GMS',license_level:0,sp:2}]);
  put('talents', [{id:'t',name:'Spotter',ranks:[{name:'I'},{name:'II'},{name:'III'}]}]);
  put('rules', {mount_fittings:{Auxiliary:['Auxiliary'],Main:['Main','Auxiliary'],Flex:['Main','Auxiliary'],Heavy:['Superheavy','Heavy','Main','Auxiliary']}});
  const skeleton = run('scaffold','--data',dir,'--pilot','Example','--frame','f');
  assert.equal(skeleton.status,0,skeleton.stderr);
  const build = JSON.parse(skeleton.stdout);
  assert.equal(build.levels.length,13);
  assert.equal(build.levels[0].frame,'f');
  assert.deepEqual(build.levels[0].mounts,[{slot:'Main/Aux',weapons:[]},{slot:'Flex',weapons:[]}]);
  put('build',build);
  assert.match(run('check',path.join(dir,'build.json'),'--data',dir).stderr,/LL1.*frame/i);
  for (const row of build.levels.slice(1)) {
    row.frame='f'; row.license=row.ll <= 3 ? `Goblin ${['','I','II','III'][row.ll]}` : `Source${row.ll} I`;
    row.talents=Array(row.ll+3).fill('t'); row.mounts=build.levels[0].mounts.map(m => ({slot:m.slot,weapons:[]}));
  }
  build.levels[0].talents=['t','t','t'];
  build.levels[0].systems=['s'];
  build.levels[0].mounts[0].weapons=['w','aux'];
  put('build',build);
  const markdown=run('page',path.join(dir,'build.json'),'--data',dir);
  assert.equal(markdown.status,0,markdown.stderr);
  assert.match(markdown.stdout,/# Example: pilot build/);
  assert.match(markdown.stdout,/LL0: Test Frame/);
  assert.match(markdown.stdout,/Shield \(2 SP\)/);
  const good=run('check',path.join(dir,'build.json'),'--data',dir);
  assert.match(good.stderr,/LL1.*excess talent/);
  build.levels[0].mounts[0].weapons=['locked','aux'];
  put('build',build);
  assert.match(run('check',path.join(dir,'build.json'),'--data',dir).stderr,/LL0.*Locked Gun.*license/i);
  build.levels[0].mounts[0].weapons=['w','aux'];
  build.levels[0].systems=['s','s','s','s'];
  put('build',build);
  assert.match(run('check',path.join(dir,'build.json'),'--data',dir).stderr,/LL0.*SP/i);
  build.levels[0].systems=['s'];
  build.levels[0].mounts[0].weapons=['w','w'];
  put('build',build);
  assert.match(run('check',path.join(dir,'build.json'),'--data',dir).stderr,/LL0.*mount/i);
  build.levels[0].mounts[0].weapons=['w','aux'];
  build.levels[1]={...build.levels[0],ll:1,license:'Goblin I',talents:['t','t','t','t'],mounts:build.levels[0].mounts.map(m => ({...m,weapons:[...m.weapons]}))};
  build.levels[1].mounts[0].weapons=['locked','aux'];
  put('build',build);
  assert.doesNotMatch(run('check',path.join(dir,'build.json'),'--data',dir).stderr,/LL1.*Locked Gun.*license/i);
  build.levels[1].license='Goblin II';
  put('build',build);
  assert.match(run('check',path.join(dir,'build.json'),'--data',dir).stderr,/LL1.*license progression/i);
  const supplement=path.join(dir,'supplement');
  fs.mkdirSync(supplement);
  fs.writeFileSync(path.join(supplement,'frames.json'),JSON.stringify([{id:'extra',name:'Extra Frame',source:'GMS',license_level:0,stats:{sp:7},mounts:['Flex']}]));
  const withSupplement=run('scaffold','--data',dir,'--supplement',supplement,'--pilot','Example','--frame','extra');
  assert.equal(withSupplement.status,0,withSupplement.stderr);
  console.log('pilot-build checks pass');
} finally { fs.rmSync(dir,{recursive:true,force:true}); }
